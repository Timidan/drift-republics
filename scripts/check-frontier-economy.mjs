// One integrated economy scenario and one failed-commission path. Stock is an explicit fixture; no human balance/playability claim.
import assert from 'node:assert/strict';
import {createWorld, addPlayer, command, advanceWorld, capacity, shipSpeed, cargoWeight, ANNEX_INPUTS, OUTPOST_INPUTS, newSeamanship, workshopLimit} from '../src/economy.ts';
import {HULLS} from '../src/boat.ts';
let now=1_800_000_000_000, w=createWorld(now);
for(const [id,kind] of [['maker','shipyard'],['buyer','foundry'],['lender','refinery']]) addPlayer(w,id,id,'bastion',kind,now);
for(const p of Object.values(w.players).filter(p=>!p.npc)) p.warehouse.bastion={timber:70,plates:50,fuel:30,repairKit:10,scrap:20};
const boat=who=>w.ships[w.players[who].selectedShip],shop=who=>w.workshops.find(s=>s.owner===who);
const act=(who,data)=>{const next=structuredClone(w); command(next,who,data,now);w=next;};
const tick=seconds=>{now+=seconds*1000;advanceWorld(w,now);};
const funds=()=>Object.values(w.players).reduce((n,p)=>n+p.marks,0)+w.deliveries.filter(d=>!['delivered','cancelled'].includes(d.status)).reduce((n,d)=>n+d.price,0)+(w.builds??[]).filter(b=>!b.launched).reduce((n,b)=>n+b.price,0);
const allocation=funds();
const craft=(who,recipe,batches=1,items=[])=>act(who,{action:'craft',workshop:shop(who).id,recipe,batches,items});
craft('maker','cargoModule',2);tick(140);
const rigs=Object.values(w.items).filter(i=>i.owner==='maker').map(i=>i.id);
assert.equal(rigs.length,2);
const before=structuredClone(w);
assert.throws(()=>craft('maker','reinforcedRig',1,[rigs[0],rigs[0]]),/different/);
assert.deepEqual(w,before,'rejected upgrade leaves both items and materials intact');
craft('maker','reinforcedRig',1,rigs);assert(rigs.every(id=>w.items[id].consumed));tick(65);
const rig=Object.values(w.items).find(i=>i.tier===2),baseSpeed=shipSpeed(w,boat('maker'));
act('maker',{action:'install',item:rig.id});
assert.equal(capacity(w,boat('maker')),HULLS.cutter.hold+8);assert.equal(shipSpeed(w,boat('maker')),baseSpeed*.75);assert.equal(cargoWeight(w,boat('maker')),2);
assert.throws(()=>act('maker',{action:'salvageItem',item:rig.id}),/Remove/);
act('maker',{action:'uninstall',kind:'cargoModule'});
const timber=w.players.maker.warehouse.bastion.timber;
act('maker',{action:'salvageItem',item:rig.id});assert(rig.id in w.items && w.items[rig.id].consumed);assert.equal(w.players.maker.warehouse.bastion.timber,timber+4);
assert.throws(()=>act('maker',{action:'salvageItem',item:rig.id}),/belong/);
const berths=workshopLimit(w,'bastion');act('maker',{action:'startAnnex'});
for(const d of w.deliveries.filter(d=>d.project&&d.to==='bastion')) act('maker',{action:'supplyCivic',delivery:d.id});
assert(w.ports.bastion.civic.annex.completedAt);assert.equal(workshopLimit(w,'bastion'),berths+2);
assert.deepEqual(w.ports.bastion.civic.annex.stock,ANNEX_INPUTS);
// Real civic orders provision the annex; the next consumption cycle activates its bonus.
for(const d of w.deliveries.filter(d=>d.civic&&!d.project&&d.to==='bastion'&&d.status==='open'&&d.good!=='fish')) act('maker',{action:'supplyCivic',delivery:d.id});
tick(1);
for(const d of w.deliveries.filter(d=>d.civic&&d.to==='bastion'&&d.status==='open'&&d.good==='repairKit')) act('maker',{action:'supplyCivic',delivery:d.id});
now=w.ports.bastion.civic.nextAt;advanceWorld(w,now);assert(w.ports.bastion.civic.annex.maintained);
const commission=name=>{act('buyer',{action:'commissionShip',builder:'maker',hull:'lighter',name,price:200});const id=w.builds.at(-1).id;act('maker',{action:'acceptBuild',build:id});act('maker',{action:'requestAdvance',build:id,principal:80,repayment:88});act('lender',{action:'fundAdvance',build:id,principal:80,repayment:88});return id;};
const lenderStart=w.players.lender.marks,build=commission('Funded runner');
for(const [good,quantity] of Object.entries({timber:8,plates:3,fuel:2})) act('maker',{action:'contributeBuild',build,good,quantity});
tick(61);assert(w.builds.find(b=>b.id===build).launched);assert.equal(w.players.lender.marks,lenderStart+8);assert.equal(w.builds.find(b=>b.id===build).finance.status,'repaid');
craft('buyer','ammunition',3);tick(90);assert.equal(w.players.buyer.warehouse.bastion.ammunition,18);
// Test ships and construction stock are loaded at their real harbor before committing the charted passage.
boat('buyer').sea=newSeamanship('barge');
act('buyer',{action:'fitGear',gear:'cannon'});act('buyer',{action:'refuel',quantity:6});
for(const [good,quantity] of Object.entries({...OUTPOST_INPUTS,ammunition:9,repairKit:1})) act('buyer',{action:'cargo',good,quantity,direction:'load'});
act('buyer',{action:'listGoods',good:'ammunition',quantity:9,price:10});
act('lender',{action:'buyListing',listing:w.listings.at(-1).id});act('lender',{action:'cargo',good:'ammunition',quantity:9,direction:'load'});
act('buyer',{action:'sailFrontier',target:'west-watch'});now=boat('buyer').voyage.arriveAt+1;advanceWorld(w,now);
assert(boat('buyer').sea.anchor && !boat('buyer').port);
act('buyer',{action:'buildOutpost',target:'west-watch',acceptRisk:true});
// Ammunition placed in this finite forward store becomes the defender's exposed stock.
act('buyer',{action:'outpostCargo',target:'west-watch',good:'ammunition',quantity:6,direction:'deposit'});
act('lender',{action:'fitGear',gear:'cannon'});act('lender',{action:'refuel',quantity:5});
act('buyer',{action:'sailFrontier',target:'corsair'});now=boat('buyer').voyage.arriveAt+1;advanceWorld(w,now);
const npc=w.outposts.find(o=>o.id==='corsair'),stockBefore=structuredClone(npc.stock);
const integrity=boat('buyer').sea.integrity;act('buyer',{action:'raid',target:'corsair',mode:'skirmish'});
assert.throws(()=>act('buyer',{action:'sailFrontier',target:'east-watch'}),/committed/);
tick(21);const raid=w.raids.at(-1);assert.equal(raid.status,'won');assert.equal(Object.values(raid.loot).reduce((a,b)=>a+b,0),6);
for(const [g,q] of Object.entries(raid.loot)) assert.equal(w.outposts.find(o=>o.id==='corsair').stock[g],stockBefore[g]-q);
assert.equal(boat('buyer').sea.integrity,integrity-10);
act('lender',{action:'sailFrontier',target:'west-watch'});now=boat('lender').voyage.arriveAt+1;advanceWorld(w,now);
const exposed=w.outposts.find(o=>o.id==='west-watch');
now=Math.ceil(Math.max(now,exposed.protectedUntil)/300000)*300000+1;advanceWorld(w,now);
const safe=structuredClone(w.players.buyer.warehouse);
act('lender',{action:'raid',target:'west-watch',mode:'skirmish'});tick(21);
assert.equal(w.raids.at(-1).status,'won');assert.equal(w.raids.at(-1).loot.ammunition,6);
assert.equal(w.outposts.find(o=>o.id==='west-watch').stock.ammunition,0);assert.deepEqual(w.players.buyer.warehouse,safe);
assert.throws(()=>act('lender',{action:'raid',target:'west-watch',mode:'skirmish'}),/protected/);
assert.equal(funds(),allocation,'crafting, construction, raids and successful lending conserve Marks');
// Key failure: a cancelled funded commission refunds the buyer and preserves unrecovered principal as debt.
act('buyer',{action:'voyage',port:'bastion',route:'hazard'});now=boat('buyer').voyage.arriveAt+1;advanceWorld(w,now);
const failed=commission('Cancelled runner');
act('maker',{action:'requestDelivery',port:'bastion',good:'timber',quantity:1,price:w.players.maker.marks,minutes:20});
const reserved=w.deliveries.at(-1).id;
act('buyer',{action:'cancelBuild',build:failed});
assert.equal(w.builds.find(b=>b.id===failed).finance.debt,80);assert.equal(w.builds.find(b=>b.id===failed).finance.status,'defaulted');
act('maker',{action:'cancelDelivery',delivery:reserved});act('maker',{action:'repayAdvance',build:failed});
assert.equal(w.builds.find(b=>b.id===failed).finance.debt,0);assert.equal(funds(),allocation);
console.log('Frontier economy passed: consumed upgrades, salvage protection, funded annex/upkeep, commission advance/repayment/default, navigable NPC and opt-in PvP raids, finite loot, protected core stock and conserved Marks. Explicit stock and hull fixtures.');
